export function createTowerMonster(floor: number): MonsterDef {
  const isMilestone = floor % 5 === 0;
  const scale = Math.pow(1.22, floor - 1);
  const pool = [
    { name: '심연의 잔영', artKey: 'wraith' },
    { name: '공허의 갑주', artKey: 'knight' },
    { name: '타락한 별의 파편', artKey: 'elemental' },
    { name: '검은 숲의 야수', artKey: 'beast' },
    { name: '심연의 대마녀', artKey: 'boss_witch' },
  ];
  const pick = pool[(floor - 1) % pool.length];
  return {
    id: `tower_${floor}`,
    name: isMilestone ? `심연 군주 · ${floor}층 수호자` : `${pick.name} (${floor}층)`,
    title: isMilestone ? '무한 심연 탑 군주' : '무한 심연 탑 수호체',
    artKey: isMilestone ? 'demon_lord' : pick.artKey,
    element: 'dark',
    hp: Math.round(320000 * scale * (isMilestone ? 1.55 : 1)),
    atk: Math.round(1800 * Math.pow(1.15, floor - 1) * (isMilestone ? 1.25 : 1)),
    def: Math.round(700 * Math.pow(1.14, floor - 1)),
    expReward: Math.round(42000 * Math.pow(1.16, floor - 1)),
    stoneReward: Math.round(36000 * Math.pow(1.18, floor - 1)),
    isBoss: isMilestone,
    heavyInterval: isMilestone ? 3 : 4,
    heavyName: '심연 파동',
    heavyMult: isMilestone ? 2.3 : 1.8,
  };
}

export function createAbyssEliteMonster(level: number, rank: number): MonsterDef {
  const scale = Math.pow(1.13, Math.max(0, level - 1)) * (1 + rank * 0.45);
  return {
    id: `abyss_elite_${level}`,
    name: '미궁의 등불 사냥꾼',
    title: '심연 탐험 정예 개체',
    artKey: 'boss_knight',
    element: 'dark',
    hp: Math.round(280 * scale),
    atk: Math.round(22 * Math.pow(1.09, Math.max(0, level - 1)) * (1 + rank * 0.25)),
    def: Math.round(9 * Math.pow(1.09, Math.max(0, level - 1))),
    expReward: Math.round(140 * scale * 0.4),
    stoneReward: Math.round(160 * scale * 0.45),
    isBoss: true,
    heavyInterval: 3,
    heavyName: '미궁의 낫격',
    heavyMult: 1.85,
    encounterQuote: '어둠 속에서 등불을 켠 죄… 네 마력째 거둬가마!',
  };
}
